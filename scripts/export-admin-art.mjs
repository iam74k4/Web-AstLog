// 公開用原画から管理画面の選択見本を192pxで書き出す。新しい絵は作らず、同じ画像を縮小する。
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { chromium } from 'playwright'
import { ROOT } from './lib/dev-server.mjs'
import { importTs } from './lib/ts-import.mjs'

const { CELESTIAL_ART } = await importTs('src/ui/celestial-art.ts')
const { BLACKHOLE_ART } = await importTs('src/ui/logo.ts')
const browser = await chromium.launch()
try {
  const page = await browser.newPage()
  const entries = {}
  const files = []
  for (const [key, art] of Object.entries({ 'black-hole': BLACKHOLE_ART, ...CELESTIAL_ART })) {
    const original = await readFile(join(ROOT, 'public', art.src.split('?')[0]))
    const data = await page.evaluate(async (base64) => {
      const img = new Image()
      img.src = `data:image/webp;base64,${base64}`
      await img.decode()
      const canvas = document.createElement('canvas')
      canvas.width = 192
      canvas.height = Math.round((192 * img.naturalHeight) / img.naturalWidth)
      canvas.getContext('2d').drawImage(img, 0, 0, canvas.width, canvas.height)
      return canvas.toDataURL('image/webp', 0.85).split(',')[1]
    }, original.toString('base64'))
    const bytes = Buffer.from(data, 'base64')
    const name = `admin-celestial-${key}.webp`
    const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 8)
    entries[key] = {
      src: `/assets/${name}?v=${hash}`,
      width: 192,
      height: Math.round((192 * art.height) / art.width),
      source: art.src,
    }
    files.push({ path: join(ROOT, 'public', 'assets', name), bytes })
  }
  for (const file of files) await writeFile(file.path, file.bytes)
  await writeFile(
    join(ROOT, 'src/ui/admin-art.ts'),
    `// Generated by scripts/export-admin-art.mjs. 原画の版を変えたら再生成する。\nexport const ADMIN_ART = ${JSON.stringify(entries, null, 2)} as const\n`,
  )
  console.log(
    `✓ 管理画面の見本: 5枚・合計 ${files.reduce((total, file) => total + file.bytes.length, 0)} bytes`,
  )
} finally {
  await browser.close()
}
